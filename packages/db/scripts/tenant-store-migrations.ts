import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";

/** Read the TenantStore migration folders in apply order. */
export function readTenantStoreMigrationFiles(
	migrationDir: string,
): Record<string, string> {
	return Object.fromEntries(
		readdirSync(migrationDir)
			.filter((name) => statSync(path.join(migrationDir, name)).isDirectory())
			.sort()
			.map((name) => [
				name,
				readFileSync(path.join(migrationDir, name, "migration.sql"), "utf8"),
			]),
	);
}

/** Render a Durable Object store's migration folders as an inlined TypeScript module. */
export function renderTenantStoreMigrations(
	migrationDir: string,
	store: { folder: string; exportName: string; label: string } = {
		folder: "tenant-store-drizzle",
		exportName: "tenantStoreMigrations",
		label: "TenantStore",
	},
): string {
	const entries = Object.entries(
		readTenantStoreMigrationFiles(migrationDir),
	).map(
		([name, sqlText]) =>
			`\t${JSON.stringify(name)}: ${JSON.stringify(sqlText)},`,
	);
	return [
		"// Generated by scripts/generate-tenant-store-migration.ts from",
		`// ${store.folder}/*/migration.sql. Do not edit by hand.`,
		"",
		`/** Ordered ${store.label} migrations for drizzle-orm/durable-sqlite \`migrate()\`. */`,
		`export const ${store.exportName}: Record<string, string> = {`,
		...entries,
		"};",
		"",
	].join("\n");
}
