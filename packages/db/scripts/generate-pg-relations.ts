/** Offline projection of the canonical relation definitions onto pg-core tables. */
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "@babel/parser";

const root = new URL("../src/schema/", import.meta.url);
const composition = readFileSync(new URL("relations.ts", root), "utf8");
const ast = parse(composition, {
	sourceType: "module",
	plugins: ["typescript"],
});
const parts: string[] = [];
for (const node of ast.program.body) {
	if (
		node.type !== "ImportDeclaration" ||
		!node.source.value.startsWith("./relations/")
	)
		continue;
	const source = readFileSync(new URL(node.source.value + ".ts", root), "utf8");
	const part = parse(source, { sourceType: "module", plugins: ["typescript"] });
	for (const declaration of part.program.body) {
		if (declaration.type === "ExportNamedDeclaration")
			parts.push(
				source
					.slice(declaration.start!, declaration.end!)
					.replace(/^export /, ""),
			);
	}
}
const definition = ast.program.body.find(
	(node) => node.type === "ExportNamedDeclaration",
);
if (!definition) throw new Error("Missing relations composition");
writeFileSync(
	new URL("../src/schema-pg/relations.ts", import.meta.url),
	[
		"// Generated by scripts/generate-pg-relations.ts from schema/relations.ts and its domain parts.",
		'import { defineRelations, defineRelationsPart } from "drizzle-orm";',
		'import * as schema from "./core";',
		"const baseRelations = defineRelations(schema);",
		...parts,
		composition.slice(definition.start!, definition.end!),
	].join("\n") + "\n",
);
