import { is, SQL, sql } from "drizzle-orm";
import { getTableConfig, PgDialect, type PgTable } from "drizzle-orm/pg-core";

const dialect = new PgDialect();
const quote = (name: string) => `"${name.replaceAll('"', '""')}"`;
/** Test DDL from the generated pg-core tables; does not apply live migrations. */
export function pgTableDdl(table: PgTable): string[] {
	const config = getTableConfig(table);
	const expressions = config.columns.map((column) => {
		let ddl = `${quote(column.name)} ${column.getSQLType()}`;
		if (column.generatedIdentity) ddl += " GENERATED BY DEFAULT AS IDENTITY";
		if (column.primary) ddl += " PRIMARY KEY";
		if (column.notNull) ddl += " NOT NULL";
		if (column.isUnique) ddl += " UNIQUE";
		if (column.default !== undefined) {
			const value = is(column.default, SQL)
				? column.default
				: column.columnType === "PgJsonb"
					? sql.raw(
							`'${JSON.stringify(column.default).replaceAll("'", "''")}'::jsonb`,
						)
					: sql`${column.default}`;
			ddl += ` DEFAULT ${dialect.sqlToQuery(value.inlineParams()).sql}`;
		}
		return ddl;
	});
	for (const pk of config.primaryKeys)
		expressions.push(
			`PRIMARY KEY (${pk.columns.map((c) => quote(c.name)).join(",")})`,
		);
	return [
		`CREATE TABLE ${quote(config.name)} (${expressions.join(",")})`,
		...config.indexes.map(
			(idx) =>
				`CREATE ${idx.config.unique ? "UNIQUE " : ""}INDEX ${quote(idx.config.name!)} ON ${quote(config.name)} (${idx.config.columns.map((c) => quote((c as { name: string }).name)).join(",")})`,
		),
	];
}
