#!/usr/bin/env bun
/**
 * Generate src/template-snapshot.ts — a static map of canonical
 * starter-template files used by the Site Builder Worker at MCP runtime
 * for the theme_resync_template + theme_diff_template tools.
 *
 * The Site Builder Worker can't `git pull` at runtime, so we bundle the
 * canonical starter into the Worker module graph as inlined strings.
 * Wrangler picks up the regular TS import like any other source file.
 *
 * Source dirs: `apps/cms/templates/{tedix,marketing}/` — the starter
 * directories staged into the Site Builder sandbox image under
 * `/workspace-templates/`. `tedix` remains the default seeded into
 * `/workspace`; `marketing` is an additive starter selected per-tenant
 * via `templateSlug`.
 *
 * Scope: every locked file + every editable scaffold file enumerated
 * in `src/template-policy.ts`. The template bun.lock must be included so
 * persistent sandboxes cannot pair a current package.json with an old lock.
 * Unlisted files such as node_modules are skipped.
 *
 * Re-run via `bun run snapshot:template`. Idempotent — overwrites the
 * snapshot file. Pass `--check` to compare the generated bytes with the
 * committed snapshot without writing. Warns (does not fail) if a constraints
 * path is missing on disk, so the studio can still ship while paths are in
 * flux.
 */

import { readFile, readdir, stat, writeFile } from "node:fs/promises";
import { dirname, extname, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
	CMS_TEMPLATE_SLUGS as TEMPLATE_SLUGS,
	type CmsTemplateSlug as TemplateSlug,
	EDITABLE_FILES,
	EDITABLE_DIRS,
	LOCKED_FILES,
	lockedFilesForTemplate,
	lockedDirsForTemplate,
} from "../src/template-policy";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT_FILE = resolve(ROOT, "src", "template-snapshot.ts");
const CHECK_ONLY = process.argv.includes("--check");

function templateDirFor(slug: TemplateSlug): string {
	return resolve(ROOT, "templates", slug);
}

const MARKETING_EDITABLE_SCAFFOLDS = ["src/pages/kontakt.astro"];
const SNAPSHOT_SOURCE_EXTENSIONS = new Set([
	".astro",
	".css",
	".ts",
	".tsx",
	".json",
	".js",
	".mjs",
	".svg",
]);

