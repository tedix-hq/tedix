export type StringKey = keyof typeof STRINGS;

export function t(key: StringKey, locale: string | null | undefined): string {
	const entry = STRINGS[key];
	const lang = (locale ?? "en") as keyof typeof entry;
	return (entry[lang] ?? entry.en) as string;
}

const OG_LOCALE_MAP: Record<string, string> = {
	en: "en_US",
	de: "de_DE",
	es: "es_ES",
	fr: "fr_FR",
	it: "it_IT",
	pt: "pt_PT",
	nl: "nl_NL",
};

export function toOgLocale(locale: string | null | undefined): string {
	if (!locale) return "en_US";
	if (OG_LOCALE_MAP[locale]) return OG_LOCALE_MAP[locale];
	const base = locale.split("-")[0]?.toLowerCase();
	if (base && OG_LOCALE_MAP[base]) return OG_LOCALE_MAP[base];
	return locale.includes("_") || locale.includes("-")
		? locale.replace("-", "_")
		: locale;
}
