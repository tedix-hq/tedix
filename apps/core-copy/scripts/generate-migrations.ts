/**
 * Generates src/migrations.generated.ts: the ordered drizzle-pg migration
 * files POST /schema applies to the core Postgres schema. Regenerate after
 * packages/db/drizzle-pg changes; src/migrations.test.ts fails on drift.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";

const MIGRATIONS_DIR = fileURLToPath(
	new URL("../../../packages/db/drizzle-pg/", import.meta.url),
);

export interface CoreCopyMigration {
	name: string;
	sql: string;
}

export function readCoreCopyMigrations(): CoreCopyMigration[] {
	return readdirSync(MIGRATIONS_DIR, { withFileTypes: true })
		.filter((entry) => entry.isDirectory())
		.map((entry) => entry.name)
		.filter((name) => existsSync(`${MIGRATIONS_DIR}${name}/migration.sql`))
		.sort()
		.map((name) => ({
			name,
			sql: readFileSync(`${MIGRATIONS_DIR}${name}/migration.sql`, "utf8"),
		}));
}

export function coreCopyMigrationSource(): string {
	const migrations = readCoreCopyMigrations();
	return `// Generated by apps/core-copy/scripts/generate-migrations.ts. Do not edit.
export interface CoreCopyMigration {
	name: string;
	sql: string;
}
export const CORE_COPY_MIGRATIONS: CoreCopyMigration[] = ${JSON.stringify(migrations)};
`;
}

if (import.meta.main) {
	const target = fileURLToPath(
		new URL("../src/migrations.generated.ts", import.meta.url),
	);
	writeFileSync(target, coreCopyMigrationSource());
	console.log(`migrations: ${readCoreCopyMigrations().length} -> ${target}`);
}
