/**
 * Tedix-owned factory lane templates.
 *
 * `create_factory` renders a lane skill from one of these: a SKILL.md whose
 * frontmatter declares the schedule and the `tedi` tools the lane may call,
 * plus `scripts/workflow.ts`. The factory's ids are rendered into the workflow
 * as one constant, so nobody edits ids by hand. Nothing here is tenant
 * specific; the goal, ids, owner and caps all come from the factory binding.
 *
 * The `report` lane: read the project's Work, run ONE owner tedi turn, file at
 * most `maxProposals` deduplicated Work Items, then post a scorecard comment on
 * the factory's health item. `{probe:true}` reads only and writes nothing.
 */

import type { FactoryTemplate } from "@tedix/api-contract/schemas/factories";

export interface FactoryLaneParams {
	slug: string;
	name: string;
	goal: string;
	cron: string;
	ownerTediId: string;
	projectId: string;
	objectiveId: string;
	healthWorkItemId: string;
	workspaceId: string | null;
	maxProposals: number;
}

export interface RenderedFactoryLane {
	title: string;
	description: string;
	summary: string;
	content: string;
	files: Record<string, string>;
}

/** The tedi tools a report lane calls; nothing else is reachable. */
export const REPORT_LANE_TOOLS = [
	"work_items_list",
	"run_tedi_turn",
	"messages_read",
	"work_item_create",
	"work_item_comment",
] as const;

const yamlString = (value: string) => JSON.stringify(value);

function reportLaneWorkflow(params: FactoryLaneParams): string {
	const factory = JSON.stringify(
		{
			slug: params.slug,
			name: params.name,
			goal: params.goal,
			ownerTediId: params.ownerTediId,
			projectId: params.projectId,
			objectiveId: params.objectiveId,
			healthWorkItemId: params.healthWorkItemId,
			workspaceId: params.workspaceId,
			maxProposals: params.maxProposals,
		},
		null,
		"\t",
	);
	return `// Generated by create_factory (template: report). Re-render instead of editing ids.
const FACTORY = ${factory};

const READ_STEP = { retries: { limit: 2, delay: "5 seconds" }, timeout: "2 minutes" };
const WRITE_STEP = { retries: { limit: 1, delay: "5 seconds" }, timeout: "2 minutes" };
const TURN_STEP = { retries: { limit: 1, delay: "10 seconds" }, timeout: "240 seconds" };
const MARKER = "FACTORY_REPORT";
const REPLY_POLLS = 20;
const PRIORITIES = ["low", "medium", "high"];

function rowsOf(value) {
	if (Array.isArray(value)) return value;
	if (!value || typeof value !== "object") return [];
	for (const key of ["data", "items", "result"]) {
		const nested = rowsOf(value[key]);
		if (nested.length) return nested;
	}
	return [];
}

function proposalKey(title) {
	return String(title)
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^-+|-+$/g, "")
		.slice(0, 80);
}

function partText(part) {
	if (typeof part === "string") return part;
	if (Array.isArray(part)) return part.map(partText).join("\\n");
	if (part && typeof part === "object") return partText(part.text ?? part.content ?? "");
	return "";
}

// Only assistant text counts: the prompt itself names the marker.
function assistantTexts(value, out, depth) {
	if (depth > 6 || !value || typeof value !== "object") return out;
	if (Array.isArray(value)) {
		for (const item of value) assistantTexts(item, out, depth + 1);
		return out;
	}
	if (typeof value.role === "string") {
		if (value.role === "assistant") out.push(partText(value.content ?? value.text));
		return out;
	}
	if (value.assistant) out.push(partText(value.assistant.content ?? value.assistant));
	for (const [key, nested] of Object.entries(value)) {
		if (key !== "assistant") assistantTexts(nested, out, depth + 1);
	}
	return out;
}

function findReport(value) {
	const texts = assistantTexts(value, [], 0);
	for (let i = texts.length - 1; i >= 0; i--) {
		const text = texts[i];
		const at = text.lastIndexOf(MARKER);
		if (at < 0) continue;
		const body = text.slice(at + MARKER.length);
		const start = body.indexOf("{");
		const end = body.lastIndexOf("}");
		if (start < 0 || end <= start) continue;
		try {
			const parsed = JSON.parse(body.slice(start, end + 1));
			if (parsed && Array.isArray(parsed.proposals)) return parsed;
		} catch {
			// Keep looking at older assistant text.
		}
	}
	return null;
}

function isDuplicateError(error) {
	const message = String(error?.message ?? error);
	return /UNIQUE|already exists|duplicate/i.test(message);
}

function prompt(cycleKey, open) {
	const lines = open.slice(0, 30).map((item) => \`- [\${item.disposition}] \${item.title}\`);
	return [
		\`You own the "\${FACTORY.name}" factory. Cycle \${cycleKey}.\`,
		\`Goal: \${FACTORY.goal}\`,
		"",
		lines.length ? "Work already in this factory's project:" : "The factory's project has no Work yet.",
		...lines,
		"",
		\`Propose at most \${FACTORY.maxProposals} new Work Items that move the goal forward today.\`,
		"Skip anything already listed above. Propose nothing if nothing is worth doing; an empty list is a valid answer.",
		"Do not create Work Items yourself: this workflow files your proposals.",
		"Reply with a short summary, then end with the marker line followed by one JSON object with keys",
		'"summary" (string) and "proposals" (array of objects with "title", "description" and "priority": low, medium or high).',
		\`The marker line is: \${MARKER}\`,
	].join("\\n");
}

export default {
	async run(event, step, env) {
		const payload = event.payload ?? {};
		const runId = env.__RUN_CONTEXT__?.runId ?? null;
		const cycleKey = await step.do("cycle-key", async () =>
			typeof payload.cycleKey === "string" && payload.cycleKey
				? payload.cycleKey
				: new Date().toISOString().slice(0, 10),
		);

		const open = await step.do("gather-project-work", READ_STEP, async () =>
			rowsOf(
				await env.MCP.tedi.work_items_list({ projectId: FACTORY.projectId, limit: 50 }),
			).map((item) => ({
				id: String(item.id ?? ""),
				title: String(item.title ?? ""),
				disposition: String(item.disposition ?? ""),
				sourceIntentId: item.sourceIntentId ? String(item.sourceIntentId) : null,
			})),
		);
		if (payload.probe === true) {
			return { probe: true, factory: FACTORY.slug, cycleKey, runId, projectWork: open.length };
		}

		const sessionKey = \`factory:\${FACTORY.slug}:\${cycleKey}\`;
		const turn = await step.do("owner-turn", TURN_STEP, async () =>
			env.MCP.tedi.run_tedi_turn({
				session_key: sessionKey,
				client_request_id: \`\${sessionKey}:turn\`,
				text: prompt(cycleKey, open),
			}),
		);
		let report = findReport(turn);
		for (let i = 0; !report && i < REPLY_POLLS; i++) {
			await step.sleep(\`await-reply-\${i}\`, "30 seconds");
			const messages = await step.do(\`read-reply-\${i}\`, READ_STEP, async () =>
				env.MCP.tedi.messages_read({ session_key: sessionKey, limit: 10 }),
			);
			report = findReport(messages);
		}

		const seen = new Set();
		for (const item of open) {
			seen.add(proposalKey(item.title));
			if (item.sourceIntentId) seen.add(item.sourceIntentId);
		}
		const created = [];
		let skipped = 0;
		const proposals = (report?.proposals ?? [])
			.filter((item) => item && typeof item.title === "string" && item.title.trim())
			.slice(0, FACTORY.maxProposals);
		for (const proposal of proposals) {
			const key = proposalKey(proposal.title);
			const intent = \`factory:\${FACTORY.slug}:proposal:\${key}\`;
			if (!key || seen.has(key) || seen.has(intent)) {
				skipped++;
				continue;
			}
			seen.add(key);
			const filed = await step.do(\`propose-\${key}\`, WRITE_STEP, async () => {
				try {
					const item = await env.MCP.tedi.work_item_create({
						title: proposal.title.trim().slice(0, 300),
						description: String(proposal.description ?? "").slice(0, 4000),
						projectId: FACTORY.projectId,
						objectiveId: FACTORY.objectiveId,
						priority: PRIORITIES.includes(proposal.priority) ? proposal.priority : "medium",
						accountableOwnerType: "tedi",
						accountableOwnerId: FACTORY.ownerTediId,
						sourceIntentId: intent,
						metadata: { factory: FACTORY.slug, cycleKey, skillRunId: runId },
					});
					return { id: String(item?.id ?? item?.data?.id ?? ""), title: proposal.title.trim() };
				} catch (error) {
					if (isDuplicateError(error)) return null;
					throw error;
				}
			});
			if (filed) created.push(filed);
			else skipped++;
		}

		const summary = typeof report?.summary === "string" ? report.summary.slice(0, 1500) : "";
		await step.do("scorecard", WRITE_STEP, async () =>
			env.MCP.tedi.work_item_comment({
				id: FACTORY.healthWorkItemId,
				body: [
					\`Scorecard \${cycleKey} (run \${runId ?? "manual"})\`,
					\`- Proposed: \${created.length} new Work Item\${created.length === 1 ? "" : "s"}\${created.length ? \`: \${created.map((item) => item.title).join("; ")}\` : ""}\`,
					\`- Skipped as duplicates: \${skipped}\`,
					\`- Work already in the project: \${open.length}\`,
					\`- Owner reply: \${report ? "received" : "missing"}\`,
					summary ? \`\\n\${summary}\` : "",
				].join("\\n"),
			}),
		);
		if (!report) {
			throw new Error(\`The owner turn returned no \${MARKER} block for session \${sessionKey}\`);
		}
		return { factory: FACTORY.slug, cycleKey, runId, created, skipped, summary };
	},
};
`;
}

function reportLane(params: FactoryLaneParams): RenderedFactoryLane {
	const title = `${params.name} factory`;
	const description = `${params.name} factory lane: reads the project's Work, asks the owner tedi for at most ${params.maxProposals} new proposals toward the goal, files them as deduplicated Work Items and posts a scorecard on the health item.`;
	const summary = `Scheduled ${params.name} factory lane (report template).`;
	const content = `---
name: ${params.slug}
description: ${yamlString(description)}
audience: ["tedi"]
capabilities:
  network: false
  mcp:
    tedi: [${REPORT_LANE_TOOLS.join(", ")}]
  schedule:
    cron: ${yamlString(params.cron)}
    params: {}
---

# ${title}

Goal: ${params.goal}

Built by \`create_factory\` from the Tedix \`report\` lane template. Each run:

1. Reads the Work already in the factory's project.
2. Runs one turn of the owner tedi with the goal and that Work.
3. Files at most ${params.maxProposals} new Work Items. A proposal whose title
   matches existing Work, or whose \`sourceIntentId\` already exists, is skipped.
4. Posts a scorecard comment on the factory's health Work Item.

A run whose owner turn returns no report fails after posting its scorecard, so
\`inspect_factory_health\` reports it as failing rather than idle.

Run it with \`{ "probe": true }\` to prove the tool path: a probe reads the
project's Work and writes nothing.

Binding: project \`${params.projectId}\`, objective \`${params.objectiveId}\`,
health item \`${params.healthWorkItemId}\`, owner tedi \`${params.ownerTediId}\`${params.workspaceId ? `, Workspace \`${params.workspaceId}\`` : ""}.
`;
	return {
		title,
		description,
		summary,
		content,
		files: { "scripts/workflow.ts": reportLaneWorkflow(params) },
	};
}

export function renderFactoryLane(
	template: FactoryTemplate,
	params: FactoryLaneParams,
): RenderedFactoryLane {
	switch (template) {
		case "report":
			return reportLane(params);
	}
}
